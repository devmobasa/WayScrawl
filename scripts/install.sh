#!/usr/bin/env bash
# Installs WayScrawl for the current user.
#
# Publishes the CLI (which also hosts the daemon and its worker processes) and the review app
# into $PREFIX/lib/wayscrawl, then links $PREFIX/bin/wayscrawl. PREFIX defaults to ~/.local.
# The build is framework-dependent: it runs on the pinned .NET 11 runtime (see global.json).
# Nothing outside PREFIX is touched; add the shortcuts from config/ to Hyprland yourself.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
prefix=${PREFIX:-$HOME/.local}
target="$prefix/lib/wayscrawl"
dotnet=dotnet
[ -x "$root/.dotnet/dotnet" ] && dotnet="$root/.dotnet/dotnet"

staging=$(mktemp -d "${TMPDIR:-/tmp}/wayscrawl-install.XXXXXX")
trap 'rm -rf "$staging"' EXIT
publish=(-c Release -r linux-x64 --no-self-contained -o "$staging/app" --nologo -v quiet)
"$dotnet" publish "$root/src/WayScrawl.Cli" "${publish[@]}"
if [ -d "$root/src/WayScrawl.Review" ]; then
    "$dotnet" publish "$root/src/WayScrawl.Review" "${publish[@]}"
fi
# Whisper.net copies native runtimes for every platform; keep Linux x64 and its CUDA build.
find "$staging/app/runtimes" -mindepth 1 -maxdepth 1 ! -name linux-x64 ! -name cuda -exec rm -rf {} +

# The apphost only searches default locations for the runtime; pin the one this build used.
dotnet_root=$(dirname "$(readlink -f "$(command -v "$dotnet")")")

# A running daemon would lose files it loads lazily: stop it (finishing any recording) and wait.
if [ -x "$target/wayscrawl" ]; then
    status=$(DOTNET_ROOT="$dotnet_root" "$target/wayscrawl" status) ||
        { echo "Could not query the WayScrawl daemon; the installation was not replaced." >&2; exit 1; }
    if [[ "$status" != *"Daemon: not running"* ]]; then
        DOTNET_ROOT="$dotnet_root" "$target/wayscrawl" shutdown ||
            { echo "The running WayScrawl daemon did not stop; the installation was not replaced." >&2; exit 1; }
        for _ in $(seq 1 60); do
            status=$(DOTNET_ROOT="$dotnet_root" "$target/wayscrawl" status) ||
                { echo "Could not query the WayScrawl daemon; the installation was not replaced." >&2; exit 1; }
            [[ "$status" == *"Daemon: not running"* ]] && break
            sleep 0.5
        done
        [[ "$status" != *"Daemon: not running"* ]] &&
            { echo "The daemon is still running; the installation was not replaced." >&2; exit 1; }
    fi
fi

mkdir -p "$prefix/lib" "$prefix/bin"
rm -rf "$target.previous"
[ -d "$target" ] && mv "$target" "$target.previous"
mv "$staging/app" "$target"
rm -rf "$target.previous"
rm -f "$prefix/bin/wayscrawl"
cat > "$prefix/bin/wayscrawl" <<LAUNCHER
#!/bin/sh
# Generated by WayScrawl's scripts/install.sh.
export DOTNET_ROOT="$dotnet_root"
exec "$target/wayscrawl" "\$@"
LAUNCHER
chmod +x "$prefix/bin/wayscrawl"
echo "Installed WayScrawl into $target (runtime $dotnet_root); command: $prefix/bin/wayscrawl"
"$prefix/bin/wayscrawl" doctor | head -3
